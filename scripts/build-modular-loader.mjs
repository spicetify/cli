import { build } from "esbuild";
import { resolve } from "node:path";

const root = process.cwd();
const entryFile = resolve(root, "src/jsHelper/modularLoader/index.ts");
const outputFile = resolve(root, "jsHelper/modularLoader.js");

const result = await build({
	banner: {
		js: "/* Generated by scripts/build-modular-loader.mjs. Do not edit directly. */",
	},
	bundle: true,
	entryPoints: [entryFile],
	format: "iife",
	legalComments: "none",
	logLevel: "silent",
	minify: true,
	outfile: outputFile,
	sourcemap: true,
	sourcesContent: true,
	target: "chrome108",
	write: false,
});

const [{ outputFiles }] = [result];
await import("node:fs").then(({ writeFileSync }) => {
	for (const f of outputFiles) writeFileSync(f.path, f.contents);
});
console.log(`built ${outputFile}`);
